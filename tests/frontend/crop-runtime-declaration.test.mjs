import test from "node:test";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";

import {
  normalizeCropRuntimeDeclarationReceipt,
} from "../../src/lib/agribrain/crop-runtime-declaration.mjs";


function canonicalize(value) {
  if (Array.isArray(value)) return value.map(canonicalize);
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.keys(value).sort().map((key) => [key, canonicalize(value[key])]),
    );
  }
  return value;
}


function receipt(overrides = {}) {
  const payload = {
    contract_version: "crop_runtime_declaration_v1",
    plot_namespace: {
      tenant_id: "tenant-1",
      farm_id: "farm-1",
      plot_id: "plot-1",
    },
    crop_cycle_id: "cycle-1",
    crop_code: "fava_bean",
    authority: "FARMER_CONFIRMED",
    declared_at: "2026-08-20T12:00:00.000Z",
    source: "authenticated_farmer_crop_identity",
    cycle_created: false,
    plant_date_asserted: false,
    ...overrides,
  };
  return {
    ...payload,
    content_hash: createHash("sha256")
      .update(JSON.stringify(canonicalize(payload)), "utf8")
      .digest("hex"),
  };
}


test("runtime crop declaration is cycle-bound and distinct from label audit", () => {
  const backendVector = receipt();
  // Fixed digest generated by the Python CropRuntimeDeclarationReceipt for
  // this exact payload; this guards cross-runtime canonicalization drift.
  assert.equal(
    backendVector.content_hash,
    "36d0873355c04fa8f224a8b8190f46c27473a412c51ce68d40d456bb630d58e5",
  );
  const result = normalizeCropRuntimeDeclarationReceipt(backendVector, {
    tenant_id: "tenant-1",
    farm_id: "farm-1",
    plot_id: "plot-1",
  });

  assert.equal(result.crop_cycle_id, "cycle-1");
  assert.equal(result.crop_code, "fava_bean");
  assert.equal(result.authority, "FARMER_CONFIRMED");
  assert.equal(result.plant_date_asserted, false);
  assert.equal(Object.isFrozen(result), true);
  assert.equal(Object.isFrozen(result.plot_namespace), true);
});


test("browser refuses mismatched namespace and implicit planting evidence", () => {
  assert.throws(
    () => normalizeCropRuntimeDeclarationReceipt(receipt(), {
      tenant_id: "tenant-1",
      farm_id: "other-farm",
      plot_id: "plot-1",
    }),
    /namespace mismatch/,
  );
  assert.throws(
    () => normalizeCropRuntimeDeclarationReceipt(receipt({
      plant_date_asserted: true,
    })),
    /cannot assert a planting date/,
  );
});


test("browser refuses a tampered runtime declaration receipt", () => {
  const valid = receipt();
  assert.throws(
    () => normalizeCropRuntimeDeclarationReceipt({
      ...valid,
      crop_code: "tomato",
    }),
    /content_hash mismatch/,
  );
});
