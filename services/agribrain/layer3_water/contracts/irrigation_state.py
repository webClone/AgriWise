"""
Layer 3.0 Irrigation Intelligence and Decision Contracts
Defines irrigation events, operational constraints, economic objectives, and optimization decisions.
"""

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Optional, Dict, Any


class IrrigationMethod(str, Enum):
    """Irrigation application technology."""
    DRIP = "DRIP"                     # High efficiency, localized wetting (eta ≈ 0.90 - 0.95)
    MICRO_SPRINKLER = "MICRO_SPRINKLER" # Moderate-high efficiency (eta ≈ 0.85)
    SPRINKLER = "SPRINKLER"           # Overhead sprinkler (eta ≈ 0.75 - 0.85)
    CENTER_PIVOT = "CENTER_PIVOT"     # Mechanized pivot (eta ≈ 0.80 - 0.90)
    SURFACE_FURROW = "SURFACE_FURROW" # Gravity furrow (eta ≈ 0.60 - 0.70)
    SURFACE_FLOOD = "SURFACE_FLOOD"   # Basin / flood (eta ≈ 0.50 - 0.60)


class WaterDecisionAction(str, Enum):
    """Recommended operational water management action."""
    HOLD = "HOLD"                                       # Adequate moisture, no irrigation required
    IRRIGATE = "IRRIGATE"                               # Critical depletion replenishment
    PREVENTATIVE_IRRIGATION = "PREVENTATIVE_IRRIGATION" # Advance irrigation ahead of heatwave/tariff spike
    CONTROLLED_DEFICIT = "CONTROLLED_DEFICIT"           # Intentional stress induction (regulated deficit)


class WaterDecisionUrgency(str, Enum):
    """Urgency level of irrigation recommendation."""
    LOW = "LOW"             # Depletion well below RAW threshold
    MEDIUM = "MEDIUM"       # Approaching RAW threshold within 48 hours
    HIGH = "HIGH"           # Transpiration limitation active (Ks < 1.0)
    CRITICAL = "CRITICAL"   # Severe root zone exhaustion (Ks < 0.40)


@dataclass(frozen=True)
class IrrigationEvent:
    """Historical or scheduled irrigation application event."""
    timestamp: datetime
    gross_depth_mm: float
    net_depth_mm: float
    method: IrrigationMethod = IrrigationMethod.DRIP
    application_efficiency: float = 0.90
    water_salinity_ec_ds_m: float = 0.8
    duration_hours: Optional[float] = None
    cost_usd: Optional[float] = None


@dataclass(frozen=True)
class IrrigationConstraints:
    """Operational, hydraulic, and regulatory constraints."""
    max_single_dose_mm: float = 45.0
    min_single_dose_mm: float = 5.0
    min_cycle_interval_hours: float = 12.0
    max_flow_rate_m3_hr: Optional[float] = None
    allocation_remaining_mm: Optional[float] = None
    low_tariff_hours_only: bool = False


@dataclass(frozen=True)
class IrrigationObjective:
    """Objective weights for Model Predictive Control (MPC) irrigation optimization.
    
    J = C_water * V_water + C_energy * V_energy + C_limitation * Sum(1 - Ks)
    """
    water_cost_weight: float = 1.0
    energy_cost_weight: float = 0.5
    transpiration_limitation_penalty_weight: float = 5.0
    deep_drainage_penalty_weight: float = 2.0
    crop_economic_priority_factor: float = 1.0


@dataclass(frozen=True)
class WaterDecision:
    """Prescriptive water decision generated by Layer 3 irrigation optimizer.
    
    Focuses strictly on water supply optimization and transpiration preservation.
    """
    action: WaterDecisionAction
    urgency: WaterDecisionUrgency
    recommended_net_mm: float                    # Net depth required in root zone (mm)
    recommended_gross_mm: float                  # Gross depth considering efficiency (mm)
    transpiration_preserved_fraction: float      # Fraction of potential transpiration preserved [0.0, 1.0]
    expected_water_limitation_reduction: float   # Predicted Delta(Ks) or Delta(T_deficit) reduction (%)
    economic_water_productivity_score: float     # m3 applied per unit transpiration saved
    confidence_score: float = 0.90
    rationale: list[str] = field(default_factory=list)
    decision_ledger: Dict[str, Any] = field(default_factory=dict)
