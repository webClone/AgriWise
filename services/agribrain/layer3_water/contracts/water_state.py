@dataclass(frozen=True)
class WaterState:
    """Unified latent water intelligence state vector X_t^L3.
    
    Consolidated state representing soil water status, fluxes, root availability, 
    historical stress memory, and forward water limitation risk.
    """
    plot_id: str
    timestamp: datetime
    
    # 1. Soil moisture profile
    soil_water: SoilWaterState
    
    # 2. Evaporative & hydrological fluxes
    fluxes: WaterFluxState
    
    # 3. Root-zone availability
    root_zone: RootZoneWaterState
    
    # 4. Historical hydraulic stress memory (for Layer 4 physiological processes)
    hydraulic_memory: HydraulicStressMemoryState = field(default_factory=HydraulicStressMemoryState)
    
    # 5. Forward water limitation forecast
    limitation_forecast: WaterLimitationForecast = field(default_factory=lambda: WaterLimitationForecast(7, [], None, [], []))
    
    # 6. Data assimilation diagnostic
    assimilation_diagnostic: Optional[AssimilationDiagnostic] = None

    # 7. Layer 2 biological boundary receipt
    vegetation_boundary: Optional[VegetationState] = None
    
    # 8. Thermal observation state
    thermal_observation: Optional[CanopyTemperatureState] = None
    
    # 9. Atmospheric driver quality
    atmospheric_quality: AtmosphericInputQuality = field(default_factory=AtmosphericInputQuality)
    
    # 10. Prescriptive water decision
    active_decision: Optional[WaterDecision] = None
    
    # 11. Quality, Authority, Uncertainty & Provenance
    schema_version: str = "3.0"
    physics_authority: WaterPhysicsAuthority = WaterPhysicsAuthority.MODELLED
    hydrology_mode: HydrologyMode = HydrologyMode.FAO56_LAYERED_BUCKET
    solver_fidelity: SolverFidelity = SolverFidelity.EMPIRICAL_BUCKET
    mass_balance_error_mm: float = 0.0
    water_confidence: WaterPhysicsConfidence = field(default_factory=WaterPhysicsConfidence)
    data_health_score: float = 1.0
    uncertainty: WaterUncertaintyBudget = field(default_factory=WaterUncertaintyBudget)
    provenance: InferenceProvenance = field(default_factory=InferenceProvenance)

    # 12. Transition & Analysis Receipts
    transition_receipt: Optional[IntervalFluxReceipt] = None
    analysis_receipt: Optional[AnalysisIncrementReceipt] = None
    posterior_demand: Optional[PotentialWaterFlux] = None

    @property
    def mass_conserved(self) -> bool:
        """Physical mass conservation status."""
        if self.transition_receipt is not None:
            return bool(self.transition_receipt.mass_conserved)
        return self.mass_balance_error_mm <= 0.05

    def to_layer4_boundary_receipt(self) -> Layer3ToLayer4BoundaryReceipt:
        """Extract canonical biophysical boundary receipt for Layer 4 Biological Engine."""
        avail_ratio = (
            (self.root_zone.total_available_water_mm - self.root_zone.root_zone_depletion_mm)
            / max(1.0, self.root_zone.total_available_water_mm)
        )
        assim_status = (
            self.assimilation_diagnostic.assimilation_method
            if self.assimilation_diagnostic and self.assimilation_diagnostic.observations_assimilated_count > 0
            else "PROGNOSTIC_MODEL"
        )
        # Root-supported boundary properties
        rz_storage = getattr(self.root_zone, "root_zone_storage_mm", 0.0)
        rz_fc = getattr(self.root_zone, "depth_weighted_theta_fc", 0.30)
        rz_wp = getattr(self.root_zone, "depth_weighted_theta_wp", 0.15)
        rz_sat = getattr(self.root_zone, "depth_weighted_theta_sat", 0.45)
        rz_depth_cm = getattr(self.root_zone, "supported_root_depth_cm", getattr(self.root_zone, "root_depth_m", 0.6) * 100.0)
        drainage_val = getattr(self.fluxes.actual, "deep_drainage_mm", 0.0) if self.fluxes else 0.0

        is_conserved = self.mass_conserved
        closure_err = self.transition_receipt.water_closure_error_mm if self.transition_receipt else self.mass_balance_error_mm
        degraded = (not is_conserved) or (self.data_health_score < 0.8)

        return Layer3ToLayer4BoundaryReceipt(
            plot_id=self.plot_id,
            timestamp=self.timestamp,
            stress_factor_ks=self.root_zone.stress_factor_ks,
            transpiration_deficit_mm=self.fluxes.actual.transpiration_deficit_mm,
            transpiration_deficit_sigma_mm=round(self.root_zone.ks_uncertainty_sigma * self.fluxes.potential.tpot_mm, 3),
            total_available_water_mm=self.root_zone.total_available_water_mm,
            readily_available_water_mm=self.root_zone.readily_available_water_mm,
            root_zone_depletion_mm=self.root_zone.root_zone_depletion_mm,
            water_availability_ratio=round(max(0.0, min(1.0, avail_ratio)), 3),
            cumulative_transpiration_deficit_mm=self.hydraulic_memory.cumulative_transpiration_deficit_mm,
            consecutive_days_under_limitation=self.hydraulic_memory.consecutive_days_under_limitation,
            severe_limitation_days_count=self.hydraulic_memory.severe_limitation_days_count,
            integrated_hydraulic_stress_index=self.hydraulic_memory.integrated_hydraulic_stress_index,
            water_stress_recovery_rate=self.hydraulic_memory.water_stress_recovery_rate,
            drought_exposure_class=self.hydraulic_memory.drought_exposure_class,
            physics_authority=self.physics_authority.value if hasattr(self.physics_authority, "value") else str(self.physics_authority),
            solver_fidelity=self.solver_fidelity.value if hasattr(self.solver_fidelity, "value") else str(self.solver_fidelity),
            water_confidence_score=self.water_confidence.overall_water_confidence,
            assimilation_status=assim_status,
            root_zone_storage_mm=rz_storage,
            theta_fc_root=rz_fc,
            theta_wp_root=rz_wp,
            theta_sat_root=rz_sat,
            supported_root_depth_cm=rz_depth_cm,
            deep_drainage_mm=drainage_val,
            mass_conserved=is_conserved,
            water_closure_error_mm=closure_err,
            is_degraded=degraded,
        )
