@dataclass(frozen=True)
class SoilWaterState:
    """Multi-layer vertical soil moisture profile and hydraulic retention parameters."""
    layer_depths_cm: List[float]                  # Discretized bottom depths (e.g. [10.0, 30.0, 60.0, 100.0, 200.0])
    theta_profile: List[float]                    # Volumetric water content per layer (m3/m3)
    field_capacity_profile: List[float]           # Field capacity theta_fc (m3/m3)
    wilting_point_profile: List[float]            # Permanent wilting point theta_wp (m3/m3)
    saturation_profile: List[float]               # Saturated water content theta_s (m3/m3)
    residual_profile: List[float]                 # Residual water content theta_r (m3/m3)
    hydraulic_conductivity_profile: List[float]   # Saturated hydraulic conductivity Ks (cm/day)
    
    # Van Genuchten retention parameters for process solvers
    van_genuchten_alpha: List[float]              # Alpha parameter (1/cm)
    van_genuchten_n: List[float]                  # Pore-size distribution index n (> 1.0)
    van_genuchten_m: List[float]                  # m = 1 - 1/n
    
    # Soil suction & unsaturated hydraulic state
    matric_potential_profile_mpa: List[float] = field(default_factory=list)          # Psi_m(z) (MPa)
    unsaturated_conductivity_profile_cm_day: List[float] = field(default_factory=list) # K(theta, z) (cm/day)

    # Infiltration and evaporation state
    infiltration: Optional[InfiltrationState] = None
    evaporation_state: Optional[SoilEvaporationState] = None
    parameter_provenance: str = "TEXTURE_PRIOR"

    @property
    def total_profile_water_mm(self) -> float:
        """Total water storage in the discretized profile (mm)."""
        tot_mm = 0.0
        prev_d = 0.0
        for theta, d in zip(self.theta_profile, self.layer_depths_cm):
            thickness_mm = (d - prev_d) * 10.0
            tot_mm += theta * thickness_mm
            prev_d = d
        return round(tot_mm, 2)

    def compute_root_zone_support(self, root_depth_cm: float) -> Tuple[float, float, float, float, float]:
        """Compute root-zone moisture storage and depth-weighted hydraulic aggregates over actual root overlap.
        
        S_root = sum_i(theta_i * delta_z_i,root)
        theta_fc_root = sum_i(theta_fc_i * delta_z_i,root) / Z_root,supported
        theta_wp_root = sum_i(theta_wp_i * delta_z_i,root) / Z_root,supported
        theta_sat_root = sum_i(theta_sat_i * delta_z_i,root) / Z_root,supported
        
        Returns:
            Tuple[float, float, float, float, float]:
            (s_root_mm, theta_fc_root, theta_wp_root, theta_sat_root, supported_root_depth_cm)
        """
        if not self.layer_depths_cm or root_depth_cm <= 0.0:
            return 0.0, 0.30, 0.15, 0.45, 0.0

        root_depth_mm = root_depth_cm * 10.0
        n_layers = len(self.layer_depths_cm)
        prev_d_mm = 0.0

        s_root_mm = 0.0
        sum_fc = 0.0
        sum_wp = 0.0
        sum_sat = 0.0
        z_supported_mm = 0.0

        for i in range(n_layers):
            d_mm = self.layer_depths_cm[i] * 10.0
            if prev_d_mm < root_depth_mm:
                active_thickness_mm = max(0.0, min(d_mm, root_depth_mm) - prev_d_mm)
                if active_thickness_mm > 0.0:
                    th = self.theta_profile[i] if i < len(self.theta_profile) else 0.0
                    fc = self.field_capacity_profile[i] if i < len(self.field_capacity_profile) else 0.30
                    wp = self.wilting_point_profile[i] if i < len(self.wilting_point_profile) else 0.15
                    sat = self.saturation_profile[i] if i < len(self.saturation_profile) else 0.45

                    s_root_mm += th * active_thickness_mm
                    sum_fc += fc * active_thickness_mm
                    sum_wp += wp * active_thickness_mm
                    sum_sat += sat * active_thickness_mm
                    z_supported_mm += active_thickness_mm
            prev_d_mm = d_mm

        if z_supported_mm <= 0.0:
            return 0.0, 0.30, 0.15, 0.45, 0.0

        return (
            round(s_root_mm, 2),
            round(sum_fc / z_supported_mm, 7),
            round(sum_wp / z_supported_mm, 7),
            round(sum_sat / z_supported_mm, 7),
            round(z_supported_mm / 10.0, 2),
        )


@dataclass(frozen=True)
class PotentialWaterFlux:
    """Atmospheric and crop potential evaporative demand."""
    et0_mm: float                                 # Reference evapotranspiration (FAO-56 Penman-Monteith)
    kcb: float                                    # Basal crop coefficient from Layer 2 canopy state
    ke: float                                     # Soil evaporation coefficient
    
    @property
    def etp_mm(self) -> float:
        """Potential crop evapotranspiration ETp = (Kcb + Ke) * ET0."""
        return round((self.kcb + self.ke) * self.et0_mm, 2)
    
    @property
    def tpot_mm(self) -> float:
        """Potential crop transpiration Tpot = Kcb * ET0."""
        return round(self.kcb * self.et0_mm, 2)
    
    @property
    def espot_mm(self) -> float:
        """Potential soil evaporation Espot = Ke * ET0."""
        return round(self.ke * self.et0_mm, 2)


@dataclass(frozen=True)
class ActualWaterFlux:
    """Actual realized hydrological and evaporative fluxes."""
    ks: float                                     # Water stress reduction factor ∈ [0.0, 1.0]
    precipitation_mm: float                       # Daily precipitation depth (mm)
    irrigation_mm: float                          # Daily net irrigation depth (mm)
    deep_drainage_mm: float                       # Percolation below root zone (mm)
    runoff_mm: float                              # Surface runoff (mm)
    capillary_rise_mm: float = 0.0                # Upward flux from shallow water table (mm)
    
    # Realized flux partitions
    actual_transpiration_mm: float = 0.0          # Tact = Ks * Tpot (mm)
    actual_soil_evaporation_mm: float = 0.0       # Esact = Ke * ET0 (mm)
    actual_eta_mm: float = 0.0                    # ETa = Tact + Esact (mm)
    transpiration_deficit_mm: float = 0.0         # Tdeficit = Tpot - Tact (mm)


@dataclass(frozen=True)
class WaterFluxState:
    """Coupled dual-state flux container separating potential demand from actual supply."""
    potential: PotentialWaterFlux
    actual: ActualWaterFlux


@dataclass(frozen=True)
class RootZoneWaterState:
    """Root zone soil water storage, availability, and stress coefficient."""
    root_depth_m: float                           # Active rooting depth Zr (m)
    root_fraction_profile: List[float]            # Vertical root density fraction per soil layer (sum = 1.0)
    root_accessibility_profile: List[float]       # Accessibility conductance weights per layer
    root_uptake_distribution_profile: List[float] # Active extraction fraction U_i = R_i * f(theta_i) (sum = 1.0)
    root_extraction_modifier_profile: List[float] # Layer stress modifiers f(theta_i) ∈ [0.0, 1.0]
    total_available_water_mm: float               # TAW = 1000 * sum((theta_fc - theta_wp) * Zr_layer) (mm)
    depletion_fraction_p: float                   # Depletion fraction p = f(crop, ETp)
    readily_available_water_mm: float             # RAW = p * TAW (mm)
    root_zone_depletion_mm: float                 # Dr = Root zone moisture deficit (mm)
    stress_factor_ks: float                       # Ks ∈ [0.0, 1.0]
