    root_zone_storage_mm: float = 0.0             # S_root = sum(theta_i * delta_z_i,root) (mm)
    depth_weighted_theta_fc: float = 0.30         # Depth-weighted FC over supported root depth
    depth_weighted_theta_wp: float = 0.15         # Depth-weighted WP over supported root depth
    depth_weighted_theta_sat: float = 0.45        # Depth-weighted Saturation over supported root depth
    supported_root_depth_cm: float = 0.0          # Supported root depth thickness (cm)


