@dataclass(frozen=True)
class HydraulicStressMemoryState:
    """Historical water limitation and hydraulic stress memory accumulator.
    
    Provides Layer 4 with biological stress duration, cumulative deficits,
    and recovery rates necessary to model physiological lag and senescence.
    """
    cumulative_transpiration_deficit_mm: float = 0.0     # Sum(T_pot - T_act) over growing cycle (mm)
    consecutive_days_under_limitation: int = 0          # Days where Ks < 0.95 continuously
    severe_limitation_days_count: int = 0               # Total days where Ks < 0.50 (severe cellular stress)
    integrated_hydraulic_stress_index: float = 0.0      # Sum((1 - Ks) * VPD) in kPa*days (evaporative amplified stress)
    water_stress_recovery_rate: float = 1.0             # dKs/dt following re-watering event
    historical_min_ks: float = 1.0                      # Lowest Ks experienced in current cycle
    drought_exposure_class: str = "NONE"                # "NONE", "ACUTE_MILD", "CHRONIC_MODERATE", "SEVERE_PROLONGED"

    @classmethod
    def step_memory(
        cls,
        prev_memory: Optional["HydraulicStressMemoryState"],
        current_ks: float,
        current_tdeficit_mm: float,
        current_vpd_kpa: float = 1.5,
    ) -> "HydraulicStressMemoryState":
        """Accumulate daily biological stress memory and classify drought exposure."""
        prev = prev_memory or cls()
        cum_def = round(prev.cumulative_transpiration_deficit_mm + current_tdeficit_mm, 2)
        
        if current_ks < 0.95:
            consec = prev.consecutive_days_under_limitation + 1
        else:
            consec = 0
            
        sev_count = prev.severe_limitation_days_count + (1 if current_ks < 0.50 else 0)
        integrated_stress = round(prev.integrated_hydraulic_stress_index + (1.0 - current_ks) * current_vpd_kpa, 3)
        min_ks = round(min(prev.historical_min_ks, current_ks), 3)
        
        # GAP-25 FIX: Recovery rate calculation with biological hysteresis
        if consec == 0:
            # Hysteresis: recovery rate decays based on severity of prior stress
            max_recovery_rate = max(0.05, 1.0 - (sev_count * 0.1))
            recovery = round(min(max_recovery_rate, max(0.0, current_ks - min_ks)), 3)
        else:
            recovery = 0.0
        
        # Exposure classification
        if consec == 0 and cum_def < 10.0:
            exp_class = "NONE"
        elif consec <= 3 and sev_count == 0:
            exp_class = "ACUTE_MILD"
        elif consec <= 10 or sev_count <= 3:
            exp_class = "CHRONIC_MODERATE"
        else:
            exp_class = "SEVERE_PROLONGED"
            
        return cls(
            cumulative_transpiration_deficit_mm=cum_def,
            consecutive_days_under_limitation=consec,
            severe_limitation_days_count=sev_count,
            integrated_hydraulic_stress_index=integrated_stress,
            water_stress_recovery_rate=recovery,
            historical_min_ks=min_ks,
            drought_exposure_class=exp_class,
        )


